/**
 * Returns a consistent avatar URL based on an ID or string hash
 */
export const getStudentAvatar = (seed = 0) => {
  const num = typeof seed === 'number' ? seed : String(seed).split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const index = Math.abs(num) % COLLEGE_IMAGES.avatars.length;
  return COLLEGE_IMAGES.avatars[index];
};

export const getFacultyAvatar = (seed = 0) => {
  const num = typeof seed === 'number' ? seed : String(seed).split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const index = Math.abs(num) % COLLEGE_IMAGES.facultyAvatars.length;
  return COLLEGE_IMAGES.facultyAvatars[index];
};

export const getDepartmentImage = (code = '') => {
  const normalized = String(code).toLowerCase();
  if (normalized.includes('cs') || normalized.includes('comp') || normalized.includes('tech')) return COLLEGE_IMAGES.departments.cs;
  if (normalized.includes('eng') || normalized.includes('ee') || normalized.includes('me')) return COLLEGE_IMAGES.departments.engineering;
  if (normalized.includes('biz') || normalized.includes('bus') || normalized.includes('econ') || normalized.includes('mba')) return COLLEGE_IMAGES.departments.business;
  if (normalized.includes('med') || normalized.includes('health') || normalized.includes('bio')) return COLLEGE_IMAGES.departments.medicine;
  if (normalized.includes('sci') || normalized.includes('math') || normalized.includes('phys')) return COLLEGE_IMAGES.departments.naturalSciences;
  return COLLEGE_IMAGES.departments.humanities;
};
